"""Step 1 - Dataset inspection.

Loads both permitted datasets, profiles schema / labels / missing values / duplicates and
writes data/processed/inspection_report.md + inspection_stats.json.

Run:  python ml/inspect_data.py
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

import pandas as pd


from ml.common import (CR_DIR, CR_GT, CR_TO_LABEL, DATA_PROCESSED, EC_TSV,  # noqa: E402
                    EXCLUDED_SOURCE_CATEGORIES, normalize_text, template_key)


def inspect_text_dataset() -> dict:
    df = pd.read_csv(EC_TSV, sep="\t", encoding="utf-8", dtype={"page_id": str})
    stats: dict = {
        "file": str(EC_TSV.relative_to(EC_TSV.parents[3])),
        "rows": int(len(df)),
        "columns": list(df.columns),
        "dtypes": {c: str(t) for c, t in df.dtypes.items()},
        "missing": {c: int(v) for c, v in df.isna().sum().items()},
        "binary_label_counts": {str(k): int(v) for k, v in df["label"].value_counts().items()},
        "category_counts": {k: int(v) for k, v in df["Pattern Category"].value_counts().items()},
        "unique_page_ids": int(df["page_id"].nunique()),
    }
    norm = df["text"].map(normalize_text)
    stats["empty_after_normalisation"] = int((norm == "").sum())
    stats["exact_duplicate_texts"] = int(norm.duplicated().sum())
    tk = norm.map(template_key)
    stats["template_duplicate_texts"] = int(tk.duplicated().sum())
    # template duplicates whose labels disagree = label noise / ambiguity
    conflicting = df.assign(tk=tk).groupby("tk")["Pattern Category"].nunique()
    stats["template_groups_with_conflicting_labels"] = int((conflicting > 1).sum())
    lens = norm.str.len()
    stats["char_length"] = {
        "min": int(lens.min()), "median": float(lens.median()), "mean": round(float(lens.mean()), 1),
        "p95": float(lens.quantile(0.95)), "max": int(lens.max()),
    }
    stats["char_length_median_by_category"] = {
        k: float(v) for k, v in df.assign(n=lens).groupby("Pattern Category")["n"].median().items()
    }
    # does a page_id mix dark and non-dark rows?
    mix = df.groupby("page_id")["label"].nunique()
    stats["page_ids_with_both_labels"] = int((mix > 1).sum())
    stats["label_consistency_check"] = bool(
        ((df["label"] == 0) == (df["Pattern Category"] == "Not Dark Pattern")).all()
    )
    stats["excluded_categories"] = {c: stats["category_counts"].get(c, 0) for c in EXCLUDED_SOURCE_CATEGORIES}
    stats["examples"] = {
        cat: df.loc[df["Pattern Category"] == cat, "text"].head(3).map(normalize_text).tolist()
        for cat in df["Pattern Category"].unique()
    }
    return stats


def inspect_screenshot_dataset() -> dict:
    gt = json.loads(CR_GT.read_text())
    label_counts = Counter(l for v in gt.values() for l in v["labels"])
    stats: dict = {
        "file": "data/raw/contextrico/groundtrue.json",
        "images_in_ground_truth": len(gt),
        "record_keys": dict(Counter(k for v in gt.values() for k in v)),
        "labels_per_image": {str(k): v for k, v in sorted(Counter(len(v["labels"]) for v in gt.values()).items())},
        "label_counts": dict(label_counts.most_common()),
        "type_field": {str(k): v for k, v in Counter(v.get("type") for v in gt.values()).items()},
        "has_benign_images": any(len(v["labels"]) == 0 for v in gt.values()),
        "images_with_segments": sum(1 for v in gt.values() if "segments" in v),
    }
    text_related = {k: label_counts.get(k, 0) for k in CR_TO_LABEL}
    stats["text_observable_label_counts"] = text_related
    img_dir = CR_DIR / "images"
    if img_dir.exists():
        files = {p.name for p in img_dir.rglob("*") if p.suffix.lower() in {".jpg", ".jpeg", ".png"}}
        stats["image_files_found"] = len(files)
        stats["gt_images_missing_on_disk"] = len(set(gt) - files)
    return stats


def write_report(text: dict, shots: dict) -> None:
    DATA_PROCESSED.mkdir(parents=True, exist_ok=True)
    (DATA_PROCESSED / "inspection_stats.json").write_text(json.dumps({"ec_darkpattern": text, "contextrico_dp": shots}, indent=2, ensure_ascii=False))
    lines = ["# Dataset Inspection Report", "", "Generated by `ml/inspect_data.py` from the raw files. No numbers are hand-typed.", ""]
    lines += ["## Dataset 1 - yamanalab/ec-darkpattern (Apache-2.0)", "",
              f"- File: `{text['file']}`", f"- Rows: {text['rows']}", f"- Columns: {text['columns']}",
              f"- Missing values: {text['missing']}", f"- Binary label counts: {text['binary_label_counts']}",
              f"- Unique page_id values: {text['unique_page_ids']} (page_ids containing both dark and non-dark rows: {text['page_ids_with_both_labels']})",
              f"- Exact duplicate texts (after whitespace normalisation): {text['exact_duplicate_texts']}",
              f"- Template duplicates (digits/case/punctuation normalised): {text['template_duplicate_texts']}",
              f"- Template groups with conflicting labels: {text['template_groups_with_conflicting_labels']}",
              f"- Character length: {text['char_length']}",
              f"- Label/category consistent (label==0 iff 'Not Dark Pattern'): {text['label_consistency_check']}", "",
              "| Pattern Category | Count | Median chars |", "|---|---|---|"]
    for k, v in text["category_counts"].items():
        lines.append(f"| {k} | {v} | {text['char_length_median_by_category'][k]} |")
    lines += ["", f"Excluded from training (too few examples): {text['excluded_categories']}", ""]
    lines += ["## Dataset 2 - ContextRico-DP (Zenodo 15036779, CC-BY-4.0)", "",
              f"- Ground truth images: {shots['images_in_ground_truth']}",
              f"- Record keys: {shots['record_keys']}", f"- Labels per image: {shots['labels_per_image']}",
              f"- Contains benign (unlabelled) images: {shots['has_benign_images']}",
              f"- Image files found on disk: {shots.get('image_files_found', 'n/a')}; missing: {shots.get('gt_images_missing_on_disk', 'n/a')}",
              "", "| Label | Images |", "|---|---|"]
    for k, v in shots["label_counts"].items():
        lines.append(f"| {k} | {v} |")
    lines += ["", f"Text-observable labels used for OCR cross-domain evaluation: {shots['text_observable_label_counts']}", ""]
    (DATA_PROCESSED / "inspection_report.md").write_text("\n".join(lines))


if __name__ == "__main__":
    t = inspect_text_dataset()
    s = inspect_screenshot_dataset()
    write_report(t, s)
    print(json.dumps({"text": {k: t[k] for k in ("rows", "category_counts", "exact_duplicate_texts", "template_duplicate_texts", "template_groups_with_conflicting_labels", "page_ids_with_both_labels")},
                      "shots": {k: s.get(k) for k in ("images_in_ground_truth", "has_benign_images", "image_files_found", "text_observable_label_counts")}}, indent=1))
